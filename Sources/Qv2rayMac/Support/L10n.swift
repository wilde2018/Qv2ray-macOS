/// Always numeric ("0 KB", never "Zero KB").
private let byteFormatter: ByteCountFormatter = {
    let f = ByteCountFormatter()
    f.countStyle = .binary
    f.allowsNonnumericFormatting = false
    f.allowedUnits = [.useKB, .useMB, .useGB, .useTB]
    return f
}()

func fmtSpeed(_ bytesPerSec: Double) -> String {
    byteFormatter.string(fromByteCount: Int64(max(0, bytesPerSec))) + "/s"
}

func fmtBytes(_ bytes: Int64) -> String {
    byteFormatter.string(fromByteCount: max(0, bytes))
}
