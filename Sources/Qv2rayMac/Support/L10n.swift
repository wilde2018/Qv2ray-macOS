        get { UserDefaults.standard.string(forKey: "pref.language") ?? "system" }
        set { UserDefaults.standard.set(newValue, forKey: "pref.language") }
    }

    private static var effectiveLang: String {
        let o = languageOverride
        if o != "system" { return o }
        let sys = Locale.preferredLanguages.first ?? "en"
        return sys.hasPrefix("zh") ? "zh-Hans" : "en"
    }

    static func tr(_ key: String) -> String {
        let table = effectiveLang == "zh-Hans" ? zh : en
        return table[key] ?? en[key] ?? key
    }

